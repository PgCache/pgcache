//! The function catalog (PGC-578): every non-aggregate `pg_proc` row, keyed
//! by schema, name and arity, so a call is judged by the overloads it can
//! name rather than by the worst case of a bare name across the database.

use std::collections::HashMap;

use ecow::EcoString;
#[cfg(feature = "proxy")]
use tokio_postgres::{Client, Error};

use crate::oid::{FunctionOid, TypeOid};
use crate::query::ast::SQL_FORM_FUNCTIONS;

/// PostgreSQL function volatility classification, ordered from the most to
/// the least cacheable: an immutable result depends only on the inputs, a
/// stable one also on database state, a volatile one can differ per call.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum FunctionVolatility {
    Immutable,
    Stable,
    Volatile,
}

impl FunctionVolatility {
    /// From `pg_proc.provolatile`.
    pub fn from_provolatile(code: &str) -> Option<Self> {
        match code {
            "i" => Some(FunctionVolatility::Immutable),
            "s" => Some(FunctionVolatility::Stable),
            "v" => Some(FunctionVolatility::Volatile),
            _ => None,
        }
    }
}

/// `pg_proc.prokind`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum FunctionKind {
    Function,
    Procedure,
    Aggregate,
    Window,
}

impl FunctionKind {
    pub fn from_prokind(code: &str) -> Option<Self> {
        match code {
            "f" => Some(FunctionKind::Function),
            "p" => Some(FunctionKind::Procedure),
            "a" => Some(FunctionKind::Aggregate),
            "w" => Some(FunctionKind::Window),
            _ => None,
        }
    }

    /// A call in a scalar position names a function (a procedure only
    /// through CALL); aggregates and window functions are judged by their
    /// position, not their volatility.
    fn is_plain(self) -> bool {
        matches!(self, FunctionKind::Function | FunctionKind::Procedure)
    }
}

/// SQL behind [`FunctionCatalog::load`]. Public so pgcache-fit's embedded
/// snapshot is generated by the identical query and cannot drift from the
/// loader; the columns are the fields of [`FunctionRow`] in order.
pub const FUNCTION_CATALOG_SQL: &str = "SELECT p.oid, n.nspname, p.proname, \
        p.pronargs, p.pronargdefaults, p.provariadic <> 0, p.provolatile::text, \
        l.lanname, p.prosecdef, p.proretset, p.prorettype, p.prokind::text \
 FROM pg_proc p \
 JOIN pg_namespace n ON p.pronamespace = n.oid \
 JOIN pg_language l ON l.oid = p.prolang";

/// One function overload, as `pg_proc` describes it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FunctionRow {
    pub oid: FunctionOid,
    pub schema: EcoString,
    pub name: EcoString,
    /// Declared parameters, defaults and the variadic array included.
    pub arg_count: u16,
    /// Trailing parameters with a default.
    pub default_count: u16,
    pub variadic: bool,
    pub volatility: FunctionVolatility,
    pub language: EcoString,
    pub security_definer: bool,
    pub returns_set: bool,
    pub return_type: TypeOid,
    pub kind: FunctionKind,
}

impl FunctionRow {
    /// Whether a call with `arg_count` arguments can name this overload:
    /// defaults may be left out, a variadic array may be empty.
    pub fn accepts(&self, arg_count: u32) -> bool {
        let declared = u32::from(self.arg_count);
        let optional = u32::from(self.default_count) + u32::from(self.variadic);
        arg_count >= declared.saturating_sub(optional) && (arg_count <= declared || self.variadic)
    }
}

/// The functions of a database, read once and shared.
#[derive(Debug, Default)]
pub struct FunctionCatalog {
    rows: Vec<FunctionRow>,
    /// Row indexes per lowercased name, every schema and arity; a name
    /// matches case-insensitively because the proxy compares what the
    /// parser downcased against what the catalog spells.
    by_name: HashMap<EcoString, Vec<u32>>,
}

impl FunctionCatalog {
    pub fn from_rows(rows: Vec<FunctionRow>) -> Self {
        let mut by_name: HashMap<EcoString, Vec<u32>> = HashMap::new();
        for (index, row) in rows.iter().enumerate() {
            by_name
                .entry(lowercased(&row.name))
                .or_default()
                .push(u32::try_from(index).unwrap_or(u32::MAX));
        }
        Self { rows, by_name }
    }

    /// Read the catalog from `client`'s database.
    #[cfg(feature = "proxy")]
    pub async fn load(client: &Client) -> Result<Self, Error> {
        let rows = client.query(FUNCTION_CATALOG_SQL, &[]).await?;
        let mut functions = Vec::with_capacity(rows.len());
        for row in &rows {
            let volatility_code: &str = row.try_get(6)?;
            let volatility = FunctionVolatility::from_provolatile(volatility_code)
                .unwrap_or(FunctionVolatility::Volatile);
            let kind_code: &str = row.try_get(11)?;
            let kind = FunctionKind::from_prokind(kind_code).unwrap_or(FunctionKind::Function);
            let arg_count: i16 = row.try_get(3)?;
            let default_count: i16 = row.try_get(4)?;
            functions.push(FunctionRow {
                oid: row.try_get(0)?,
                schema: EcoString::from(row.try_get::<_, &str>(1)?),
                name: EcoString::from(row.try_get::<_, &str>(2)?),
                arg_count: u16::try_from(arg_count).unwrap_or(0),
                default_count: u16::try_from(default_count).unwrap_or(0),
                variadic: row.try_get(5)?,
                volatility,
                language: EcoString::from(row.try_get::<_, &str>(7)?),
                security_definer: row.try_get(8)?,
                returns_set: row.try_get(9)?,
                return_type: row.try_get(10)?,
                kind,
            });
        }
        Ok(Self::from_rows(functions))
    }

    pub fn len(&self) -> usize {
        self.rows.len()
    }

    pub fn is_empty(&self) -> bool {
        self.rows.is_empty()
    }

    pub fn rows(&self) -> &[FunctionRow] {
        &self.rows
    }

    /// Every overload of `name`, in any schema and of any arity.
    pub fn named<'s>(&'s self, name: &str) -> impl Iterator<Item = &'s FunctionRow> + use<'s> {
        self.by_name
            .get(lowercased(name).as_str())
            .into_iter()
            .flatten()
            .filter_map(|index| self.rows.get(*index as usize))
    }

    /// The overloads a call can name: those of `name` taking `arg_count`
    /// arguments, in `schema` when the call is qualified, else in any schema
    /// (which one the search_path picks is the writer's resolution).
    pub fn candidates<'s>(
        &'s self,
        schema: Option<&'s str>,
        name: &str,
        arg_count: u32,
    ) -> impl Iterator<Item = &'s FunctionRow> + use<'s> {
        self.named(name).filter(move |row| {
            row.accepts(arg_count) && schema.is_none_or(|schema| row.schema == schema)
        })
    }

    /// The candidates of a call made with `search_path` in force: a bare
    /// name is found in `pg_catalog`, which PostgreSQL searches first
    /// whether or not it is listed, and in the path's schemas; every match
    /// counts, since without argument types the one PostgreSQL would pick
    /// is unknown.
    pub fn on_path<'s>(
        &'s self,
        schema: Option<&'s str>,
        name: &str,
        arg_count: u32,
        search_path: &'s [&'s str],
    ) -> impl Iterator<Item = &'s FunctionRow> + use<'s> {
        self.candidates(schema, name, arg_count).filter(move |row| {
            schema.is_some()
                || row.schema == "pg_catalog"
                || search_path.contains(&row.schema.as_str())
        })
    }

    /// The least cacheable volatility among the builtin functions a call can
    /// name (the cache PG has no others), the parser's own forms counted as
    /// immutable; `None` when no builtin fits the call.
    pub fn builtin_worst_volatility(
        &self,
        schema: Option<&str>,
        name: &str,
        arg_count: u32,
    ) -> Option<FunctionVolatility> {
        if schema.is_none_or(|schema| schema == "pg_catalog") && is_sql_form(name) {
            return Some(FunctionVolatility::Immutable);
        }
        self.candidates(schema, name, arg_count)
            .filter(|row| row.oid.is_builtin() && row.kind.is_plain())
            .map(|row| row.volatility)
            .max()
    }

    /// The least cacheable volatility among every overload of `name`: what a
    /// call of the name could do at worst, whatever it resolves to.
    pub fn name_worst_volatility(&self, name: &str) -> Option<FunctionVolatility> {
        self.named(name).map(|row| row.volatility).max()
    }
}

/// Whether `name` is a form the parser spells as a function call without a
/// `pg_proc` row behind it (`coalesce`, `nullif`, ...): evaluated by the
/// executor itself, so immutable and present on every PostgreSQL.
pub fn is_sql_form(name: &str) -> bool {
    SQL_FORM_FUNCTIONS
        .iter()
        .any(|form| form.eq_ignore_ascii_case(name))
}

fn lowercased(name: &str) -> EcoString {
    if name.bytes().any(|b| b.is_ascii_uppercase()) {
        EcoString::from(name.to_lowercase())
    } else {
        EcoString::from(name)
    }
}

#[cfg(test)]
impl FunctionRow {
    /// A `pg_catalog` function of `name` that accepts any number of
    /// arguments, for tests that care about volatility alone.
    pub(crate) fn test_builtin(name: &str, volatility: FunctionVolatility) -> Self {
        Self {
            oid: FunctionOid::from_raw(1),
            schema: EcoString::from("pg_catalog"),
            name: EcoString::from(name),
            arg_count: 1,
            default_count: 0,
            variadic: true,
            volatility,
            language: EcoString::from("internal"),
            security_definer: false,
            returns_set: false,
            return_type: TypeOid::UNSPECIFIED,
            kind: FunctionKind::Function,
        }
    }

    /// A user-defined function in `schema` accepting any number of arguments.
    pub(crate) fn test_user(schema: &str, name: &str, volatility: FunctionVolatility) -> Self {
        Self {
            oid: FunctionOid::from_raw(20_000),
            schema: EcoString::from(schema),
            ..Self::test_builtin(name, volatility)
        }
    }
}

#[cfg(test)]
impl FunctionCatalog {
    pub(crate) fn test_builtins<'a>(
        functions: impl IntoIterator<Item = (&'a str, FunctionVolatility)>,
    ) -> Self {
        Self::from_rows(
            functions
                .into_iter()
                .map(|(name, volatility)| FunctionRow::test_builtin(name, volatility))
                .collect(),
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(
        oid: u32,
        schema: &str,
        name: &str,
        arg_count: u16,
        default_count: u16,
        variadic: bool,
        volatility: FunctionVolatility,
    ) -> FunctionRow {
        FunctionRow {
            oid: FunctionOid::from_raw(oid),
            schema: EcoString::from(schema),
            name: EcoString::from(name),
            arg_count,
            default_count,
            variadic,
            volatility,
            language: EcoString::from("sql"),
            security_definer: false,
            returns_set: false,
            return_type: TypeOid::UNSPECIFIED,
            kind: FunctionKind::Function,
        }
    }

    fn catalog() -> FunctionCatalog {
        FunctionCatalog::from_rows(vec![
            row(
                100,
                "pg_catalog",
                "lower",
                1,
                0,
                false,
                FunctionVolatility::Immutable,
            ),
            row(
                20000,
                "app",
                "lower",
                1,
                0,
                false,
                FunctionVolatility::Stable,
            ),
            row(
                101,
                "pg_catalog",
                "concat",
                1,
                0,
                true,
                FunctionVolatility::Immutable,
            ),
            row(
                102,
                "pg_catalog",
                "substring",
                3,
                1,
                false,
                FunctionVolatility::Immutable,
            ),
            row(
                103,
                "pg_catalog",
                "now",
                0,
                0,
                false,
                FunctionVolatility::Stable,
            ),
            row(
                20001,
                "app",
                "RI_Check",
                2,
                0,
                false,
                FunctionVolatility::Volatile,
            ),
            row(
                20002,
                "app",
                "lower",
                2,
                0,
                false,
                FunctionVolatility::Immutable,
            ),
        ])
    }

    /// Defaults may be left out and a variadic array may be empty, so
    /// arity is a range per overload.
    #[test]
    fn test_arity_accepts_defaults_and_variadics() {
        let c = catalog();
        let names = |schema, name, n| {
            c.candidates(schema, name, n)
                .map(|r| r.oid.get())
                .collect::<Vec<_>>()
        };
        assert_eq!(names(None, "substring", 2), [102]);
        assert_eq!(names(None, "substring", 3), [102]);
        assert!(names(None, "substring", 1).is_empty());
        assert!(names(None, "substring", 4).is_empty());
        assert_eq!(names(None, "concat", 0), [101]);
        assert_eq!(names(None, "concat", 7), [101]);
        assert_eq!(names(None, "now", 0), [103]);
        assert!(names(None, "now", 1).is_empty());
    }

    /// Only builtins count for the proxy's verdict: a user overload neither
    /// rescues nor condemns a bare name, and a qualified user function is
    /// unknown. The whole-name worst case still sees every overload.
    #[test]
    fn test_builtin_worst_volatility_ignores_user_functions() {
        let c = catalog();
        assert_eq!(
            c.builtin_worst_volatility(None, "lower", 1),
            Some(FunctionVolatility::Immutable)
        );
        assert_eq!(
            c.builtin_worst_volatility(Some("pg_catalog"), "lower", 1),
            Some(FunctionVolatility::Immutable)
        );
        assert_eq!(c.builtin_worst_volatility(Some("app"), "lower", 1), None);
        assert_eq!(c.builtin_worst_volatility(None, "lower", 2), None);
        assert_eq!(c.builtin_worst_volatility(None, "missing", 1), None);
        assert_eq!(
            c.name_worst_volatility("lower"),
            Some(FunctionVolatility::Stable)
        );
    }

    /// `coalesce` and the other forms the parser spells as calls have no
    /// `pg_proc` row and are immutable wherever they stand.
    #[test]
    fn test_sql_forms_are_immutable_builtins() {
        let c = catalog();
        for form in ["coalesce", "COALESCE", "nullif", "greatest", "least"] {
            assert_eq!(
                c.builtin_worst_volatility(None, form, 3),
                Some(FunctionVolatility::Immutable),
                "{form}"
            );
        }
        assert_eq!(c.builtin_worst_volatility(Some("app"), "coalesce", 2), None);
    }

    /// A bare call sees pg_catalog and the path's schemas; a qualified
    /// call only its schema.
    #[test]
    fn test_on_path_candidates() {
        let c = catalog();
        let oids = |schema, name, n, path: &[&str]| {
            let mut oids: Vec<u32> = c
                .on_path(schema, name, n, path)
                .map(|row| row.oid.get())
                .collect();
            oids.sort_unstable();
            oids
        };
        assert_eq!(oids(None, "lower", 1, &["public"]), [100]);
        assert_eq!(oids(None, "lower", 1, &["app", "public"]), [100, 20000]);
        assert_eq!(oids(None, "lower", 2, &["public"]), Vec::<u32>::new());
        assert_eq!(oids(Some("app"), "lower", 1, &["public"]), [20000]);
        assert_eq!(oids(None, "ri_check", 2, &["app"]), [20001]);
    }

    /// The parser downcases an unquoted name; the catalog may not spell it
    /// that way.
    #[test]
    fn test_name_lookup_is_case_insensitive() {
        let c = catalog();
        assert_eq!(
            c.name_worst_volatility("ri_check"),
            Some(FunctionVolatility::Volatile)
        );
        assert_eq!(
            c.builtin_worst_volatility(None, "LOWER", 1),
            Some(FunctionVolatility::Immutable)
        );
    }

    #[test]
    fn test_builtin_oid_boundary() {
        assert!(FunctionOid::from_raw(16383).is_builtin());
        assert!(!FunctionOid::from_raw(16384).is_builtin());
    }
}
