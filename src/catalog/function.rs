    /// A body is inlined for the one function a call can name: a qualified
    /// call's function, or a bare name no other function in the catalog
    /// shares; a builtin or a second overload of the name leaves the call
    /// as it is, and so does a function without a body.
    #[test]
    fn test_inline_body_needs_one_candidate() {
        let sql = |text: &str| FunctionSource {
            text: EcoString::from(text),
            strict: false,
            has_config: false,
            arg_names: Vec::new(),
            arg_types: vec![EcoString::from("integer")],
            return_type: EcoString::from("integer"),
        };
        let c = FunctionCatalog::from_rows(vec![
            FunctionRow {
                source: Some(sql("select $1 + 1")),
                ..row(
                    20_000,
                    "app",
                    "incr",
                    1,
                    0,
                    false,
                    FunctionVolatility::Stable,
                )
            },
            FunctionRow {
                source: Some(sql("select $1")),
                ..row(
                    100,
                    "pg_catalog",
                    "abs",
                    1,
                    0,
                    false,
                    FunctionVolatility::Immutable,
                )
            },
            FunctionRow {
                source: Some(sql("select $1 - 1")),
                ..row(
                    20_001,
                    "app",
                    "abs",
                    1,
                    0,
                    false,
                    FunctionVolatility::Stable,
                )
            },
            FunctionRow {
                source: Some(sql("select $1 * 2")),
                ..row(
                    20_002,
                    "app",
                    "twice",
                    1,
                    0,
                    false,
                    FunctionVolatility::Stable,
                )
            },
            FunctionRow {
                source: Some(sql("select $1 * 2")),
                ..row(
                    20_003,
                    "other",
                    "twice",
                    1,
                    0,
                    false,
                    FunctionVolatility::Stable,
                )
            },
            row(
                20_004,
                "app",
                "opaque",
                1,
                0,
                false,
                FunctionVolatility::Stable,
            ),
        ]);
        let oid = |schema, name| c.inline_body(schema, name, 1).map(|body| body.oid.get());
        assert_eq!(oid(None, "incr"), Some(20_000));
        assert_eq!(oid(Some("app"), "incr"), Some(20_000));
        assert_eq!(oid(Some("other"), "incr"), None);
        assert_eq!(oid(None, "abs"), None, "a builtin shares the name");
        assert_eq!(oid(Some("app"), "abs"), Some(20_001));
        assert_eq!(oid(None, "twice"), None, "two schemas answer");
        assert_eq!(oid(Some("other"), "twice"), Some(20_003));
        assert_eq!(oid(None, "opaque"), None, "no body");
        assert!(c.inline_body(None, "incr", 2).is_none(), "arity");
    }

    /// A call records the definition it was inlined from; a catalog loaded
    /// after a redefinition of the function no longer vouches for it.
    #[test]
    fn test_inlined_call_is_current_until_the_row_changes() {
        let sql = |text: &str| FunctionSource {
            text: EcoString::from(text),
            strict: false,
            has_config: false,
            arg_names: Vec::new(),
            arg_types: Vec::new(),
            return_type: EcoString::from("integer"),
        };
        let catalog_with = |text: &str| {
            FunctionCatalog::from_rows(vec![FunctionRow {
                source: Some(sql(text)),
                ..row(20_000, "app", "f", 0, 0, false, FunctionVolatility::Stable)
            }])
        };
        let before = catalog_with("select 1");
        let body = before.inline_body(None, "f", 0).expect("body");
        let call = InlinedCall {
            schema: None,
            name: EcoString::from("f"),
            arg_count: 0,
            oid: body.oid,
            definition: body.definition,
        };
        assert!(before.inlined_call_is_current(&call));
        assert!(!catalog_with("select 2").inlined_call_is_current(&call));
        assert!(
            !FunctionCatalog::from_rows(vec![row(
                20_000,
                "app",
                "f",
                0,
                0,
                false,
                FunctionVolatility::Stable,
            )])
            .inlined_call_is_current(&call),
            "the body is gone"
        );
    }

